def canonical(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def run(*command: str, cwd: Path = REPO, env: dict | None = None) -> None:
    subprocess.run(command, cwd=cwd, env=env, check=True)


def output(*command: str, cwd: Path = REPO) -> str:
    return subprocess.check_output(command, cwd=cwd, text=True).strip()


def write_json(path: Path, value: object) -> None:
    path.write_bytes(json.dumps(value, sort_keys=True, indent=2).encode() + b"\n")


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def wheel_payload(path: Path) -> dict[str, bytes]:
    with zipfile.ZipFile(path) as archive:
        names = archive.namelist()
        require(len(names) == len(set(names)), "Duplicate wheel member")
        require(
            all(not n.startswith("/") and ".." not in Path(n).parts for n in names),
            "Unsafe wheel member",
        )
        return {name: archive.read(name) for name in names if not name.endswith("/")}


def validate_payload(payload: dict[str, bytes]) -> None:
    for path, markers in MARKERS.items():
        require(path in payload, f"Missing {path}")
        for marker in markers:
            require(marker in payload[path], f"Missing required marker in {path}: {marker!r}")
    require(UI + "index.html" in payload, "Missing built UI index")
    scripts = b"\n".join(v for k, v in payload.items() if k.startswith(UI) and k.endswith(".js"))
    require(b"mcp-server" in scripts and b"connection_url" in scripts, "Missing native MCP UI")
    require(
        re.search(
            rb"displayName:.OpenCode.,iconKind:.opencode.,sortRank:25,capabilities:\[.modelPicker.",
            scripts,
        )
        is not None,
        "Missing OpenCode model picker UI",
    )
    metadata = payload.get("omnigent-0.21.0.dist-info/METADATA", b"")
    require(b"\nVersion: 0.21.0\n" in metadata, "Core package version must remain 0.21.0")


def normalize_wheel(path: Path, identity: dict) -> dict[str, str]:
    payload = wheel_payload(path)
    with zipfile.ZipFile(path) as archive:
        executable = {
            item.filename for item in archive.infolist() if item.external_attr >> 16 & 0o111
        }
    record = "omnigent-0.21.0.dist-info/RECORD"
    payload.pop(record, None)
    epoch = identity["sourceDateEpoch"]
    payload["omnigent/_build_info.py"] = (
        '"""Generated by the WOOW portable wheel builder."""\n'
        f"BUILD_TIME_EPOCH: int = {epoch}\n"
        f"COMMIT_SHA: str = {identity['sourceCommit'] or ''!r}\n"
    ).encode()
    payload["omnigent/_woow_build.json"] = canonical(identity) + b"\n"
    validate_payload(payload)
    manifest = {name: sha256(data) for name, data in sorted(payload.items())}
    rows = io.StringIO(newline="")
    writer = csv.writer(rows, lineterminator="\n")
    for name, data in sorted(payload.items()):
        digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()
        writer.writerow([name, "sha256=" + digest, len(data)])
    writer.writerow([record, "", ""])
    payload[record] = rows.getvalue().encode()
    timestamp = time.gmtime(max(epoch, 315532800))[:6]
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in sorted(payload.items()):
            info = zipfile.ZipInfo(name, timestamp)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = (0o100755 if name in executable else 0o100644) << 16
            archive.writestr(info, data, compresslevel=9)
    return manifest


def export_source(destination: Path, commit: str, snapshot: bool) -> dict[str, str]:
    if snapshot:
        paths = (
            subprocess.check_output(
                ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=REPO
            )
            .decode()
            .split("\0")
        )
        for name in sorted(set(paths) - {""}):
            source = REPO / name
            if not source.exists() and not source.is_symlink():
                continue
            target = destination / name
            target.parent.mkdir(parents=True, exist_ok=True)
            if source.is_symlink():
                target.symlink_to(os.readlink(source))
            elif source.is_file():
                shutil.copy2(source, target)
    else:
        with tempfile.TemporaryFile() as archive:
            subprocess.run(["git", "archive", commit], cwd=REPO, stdout=archive, check=True)
            archive.seek(0)
            with tarfile.open(fileobj=archive) as source:
                source.extractall(destination, filter="data")
    return {
        str(path.relative_to(destination)): sha256(
            os.readlink(path).encode() if path.is_symlink() else path.read_bytes()
        )
        for path in sorted(destination.rglob("*"))
        if path.is_file() or path.is_symlink()
    }


def build(args: argparse.Namespace) -> None:
    require(
        ".".join(map(str, sys.version_info[:3])) == BUILD_PYTHON,
        f"Run the builder with Python {BUILD_PYTHON}",
    )
    commit = output("git", "rev-parse", "HEAD" if args.snapshot else args.source_commit)
    require(re.fullmatch(r"[0-9a-f]{40}", commit) is not None, "Need full immutable source SHA")
    if not args.snapshot:
        require(commit == args.source_commit, "Supply a full source commit, not a branch/tag")
    require(output("node", "--version") == NODE_VERSION, f"Build requires Node {NODE_VERSION}")
    require(output("uv", "--version").split()[1] == UV_VERSION, f"Build requires uv {UV_VERSION}")
    pnpm = ["pnpm"] if shutil.which("pnpm") else ["npx", "--yes", f"pnpm@{PNPM_VERSION}"]
    require(output(*pnpm, "--version") == PNPM_VERSION, "Unexpected pnpm version")
    artifact = args.output.resolve()
    require(not artifact.exists() or not any(artifact.iterdir()), "Output must be empty")
    artifact.mkdir(parents=True, exist_ok=True)
    epoch = int(output("git", "show", "-s", "--format=%ct", commit))
    with tempfile.TemporaryDirectory(prefix="woow-mcp-build-") as temporary:
        root = Path(temporary)
        source = root / "source"
        source.mkdir()
        inputs = export_source(source, commit, args.snapshot)
        identity = {
            "schemaVersion": 1,
            "buildId": args.build_id,
            "coreVersion": "0.21.0",
            "sourceCommit": None if args.snapshot else commit,
            "sourceBaseCommit": commit,
            "sourceTreeSha256": sha256(canonical(inputs)),
            "sourceDateEpoch": epoch,
            "publishable": not args.snapshot,
        }
        env = {
            **os.environ,
            "SOURCE_DATE_EPOCH": str(epoch),
            "PYTHONHASHSEED": "0",
            "TZ": "UTC",
            "COREPACK_ENABLE_DOWNLOAD_PROMPT": "0",
            "VITE_OMNIGENT_HOST_ROUTING": "false",
            "OMNIGENT_SKIP_WEB_UI": "true",
        }
        # Build in a fresh tree: setup.py's cached-UI shortcut cannot select stale assets.
        run(*pnpm, "install", "--frozen-lockfile", "--filter", "web", cwd=source, env=env)
        run(*pnpm, "--filter", "web", "run", "build", cwd=source, env=env)
        builder = root / "builder"
        run("uv", "venv", "--python", BUILD_PYTHON, str(builder), cwd=source, env=env)
        python = str(builder / "bin/python")
        run(
            "uv",
            "pip",
            "install",
            "--python",
            python,
            "--require-hashes",
            "--no-deps",
            "--only-binary",
            ":all:",
            "-r",
            str(source / "deploy/docker/woowtech-wheel-build-requirements.txt"),
            cwd=source,
            env=env,
        )
        run(
            "uv",
            "build",
            "--wheel",
            "--no-build-isolation",
            "--python",
            python,
            "--out-dir",
            str(artifact),
            cwd=source,
            env=env,
        )
        files = normalize_wheel(artifact / WHEEL, identity)
        manifest = {"schemaVersion": 1, "files": files, "sourceFiles": inputs}
        write_json(artifact / MANIFEST, manifest)
        ui = {name: digest for name, digest in files.items() if name.startswith(UI)}
        receipt = {
            **identity,
            "wheelFilename": WHEEL,
            "wheelSha256": sha256((artifact / WHEEL).read_bytes()),
            "uiSha256": sha256(canonical(ui)),
            "contentSha256": sha256(canonical(files)),
            "contentManifestSha256": sha256((artifact / MANIFEST).read_bytes()),
            "migrationHead": MIGRATION,
            "architecture": "py3-none-any",
            "dependencyLocks": {
                name: inputs[name]
                for name in (
                    "uv.lock",
                    "pnpm-lock.yaml",
                    "pnpm-workspace.yaml",
                    "deploy/docker/woowtech-wheel-build-requirements.txt",
                )
            },
            "tools": {
                "node": NODE_VERSION,
                "pnpm": PNPM_VERSION,
                "python": BUILD_PYTHON,
                "uv": output("uv", "--version"),
            },
            "ci": {
                key: os.environ.get(key)
                for key in (
                    "GITHUB_REPOSITORY",
                    "GITHUB_RUN_ID",
                    "GITHUB_RUN_ATTEMPT",
                    "GITHUB_SHA",
                )
            },
        }
        write_json(artifact / RECEIPT, receipt)
        (artifact / "SHA256SUMS").write_text(
            "".join(
                f"{sha256((artifact / name).read_bytes())}  {name}\n"
                for name in (WHEEL, RECEIPT, MANIFEST)
            )
        )
    verify(artifact, args.source_commit if not args.snapshot else None)
    print(json.dumps({"artifact": str(artifact), **receipt}, indent=2))


def verify(artifact: Path, source_commit: str | None = None) -> tuple[dict, dict]:
    receipt = json.loads((artifact / RECEIPT).read_text())
    manifest_bytes = (artifact / MANIFEST).read_bytes()
    require(
        sha256(manifest_bytes) == receipt["contentManifestSha256"],
        "Content manifest hash mismatch",
    )
    manifest = json.loads(manifest_bytes)
    require(receipt["wheelFilename"] == WHEEL, "Unexpected wheel filename")
    require(
        sha256((artifact / WHEEL).read_bytes()) == receipt["wheelSha256"], "Wheel hash mismatch"
    )
    if source_commit:
        require(
            receipt["publishable"] and receipt["sourceCommit"] == source_commit,
            "Receipt does not match immutable source commit",
        )
    payload = wheel_payload(artifact / WHEEL)
    validate_payload(payload)
    files = {
        name: sha256(data)
        for name, data in payload.items()
        if not name.endswith(".dist-info/RECORD")
    }
    require(files == manifest["files"], "Wheel content differs from manifest")
    require(sha256(canonical(files)) == receipt["contentSha256"], "Content hash mismatch")
    require(
        sha256(canonical(manifest["sourceFiles"])) == receipt["sourceTreeSha256"],
        "Source hash mismatch",
    )
    require(
        sha256(canonical({k: v for k, v in files.items() if k.startswith(UI)}))
        == receipt["uiSha256"],
        "UI hash mismatch",
    )
    identity = json.loads(payload["omnigent/_woow_build.json"])
    require(
        all(receipt[key] == value for key, value in identity.items()), "Embedded source mismatch"
    )
    return receipt, manifest


def runtime(args: argparse.Namespace) -> None:
    receipt, manifest = verify(args.artifact, args.source_commit)
    require(importlib.metadata.version("omnigent") == "0.21.0", "Wrong installed core version")
    package = importlib.import_module("omnigent")
    root = Path(package.__file__).resolve().parent.parent
    for name, digest in manifest["files"].items():
        if name.startswith("omnigent/"):
            require(
                sha256((root / name).read_bytes()) == digest, f"Installed content differs: {name}"
            )
    for name in (
        "omnigent.server.mcp_server",
        "omnigent.server.mcp_profile_store",
        "omnigent.server.routes.mcp_server_profiles",
    ):
        importlib.import_module(name)
    app = importlib.import_module("omnigent.server.app")
    require(
        "public_api_docs" in inspect.signature(app.create_app).parameters,
        "Public API docs policy argument missing",
    )
    host_store = importlib.import_module("omnigent.stores.host_store")
    require(
        "require_offline" in inspect.signature(host_store.HostStore.delete_host).parameters,
        "Host deletion offline guard missing",
    )
    require(app._is_web_ui_history_fallback_path("c/conv_abc123"), "SPA route broken")
    require(app._is_web_ui_history_fallback_path("grid/grid_abc123"), "Grid SPA route broken")
    require(not app._is_web_ui_history_fallback_path("wp-admin"), "Public route guard missing")
    if args.debian_security:
        require(
            importlib.metadata.version("oauthlib") == "4.0.1", "Wrong oauthlib security version"
        )
        require(importlib.metadata.version("pip") == "26.3", "Wrong pip security version")
    print(
        json.dumps(
            {
                "verifiedSource": receipt["sourceCommit"],
                "wheelSha256": receipt["wheelSha256"],
                "installedPackage": str(root / "omnigent"),
            }
        )
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    builder = commands.add_parser("build")
    source = builder.add_mutually_exclusive_group(required=True)
    source.add_argument("--source-commit")
    source.add_argument("--snapshot", action="store_true")
    builder.add_argument("--build-id", default="mcp.1")
    builder.add_argument("--output", type=Path, required=True)
    for name in ("verify", "runtime"):
        verifier = commands.add_parser(name)
        verifier.add_argument("--artifact", type=Path, required=True)
        verifier.add_argument("--source-commit")
        if name == "runtime":
            verifier.add_argument("--debian-security", action="store_true")
    args = parser.parse_args()
    if args.command == "build":
        build(args)
    elif args.command == "runtime":
        runtime(args)
    else:
        receipt, _ = verify(args.artifact, args.source_commit)
        print(
            json.dumps(
                {"sourceCommit": receipt["sourceCommit"], "wheelSha256": receipt["wheelSha256"]}
            )
        )


if __name__ == "__main__":
    main()
